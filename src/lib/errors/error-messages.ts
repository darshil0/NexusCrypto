export function createAppError(
  code: AppErrorCode,
  customMessage?: string,
  details?: Record<string, unknown>
): AppError {
  const base = ERROR_CATALOG[code] || ERROR_CATALOG.UNKNOWN_ERROR;
  return {
    ...base,
    message: customMessage || base.message,
    details,
  };
}
